const generatedName = /(?:^|[.-])(?:gen|generated)\./u;
const generatedDirectory = /(?:^|[/\\])(?:_generated|__generated__|generated)(?:[/\\]|$)/u;
const leadingComments = /^\s*(?:(?:\/\/[^\r\n]*(?:\r\n|\r|\n|$)|\/\*[\s\S]*?\*\/|#[^\r\n]*(?:\r\n|\r|\n|$))\s*)+/u;
const generatedHeader = /^\s*(?:\/\/|\/\*|\*|#)?\s*(?:@generated\b|(?:This (?:file|code) (?:is|was) )?(?:auto[- ]?generated|automatically generated)\b|(?:This (?:file|code) (?:is|was) )?generated by\b|Code generated\b.*DO NOT EDIT\b)/imu;

export default function isGeneratedSource(filename, source) {
	const name = filename.split(/[/\\]/u).at(-1);
	const banner = source.match(leadingComments)?.[0] ?? "";
	return generatedName.test(name) || generatedDirectory.test(filename) || generatedHeader.test(banner);
}
